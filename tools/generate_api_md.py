import json
import sys
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = REPO_ROOT / "docs" / "MACHINE_READABLE_API.json"
DEFAULT_OUTPUT = REPO_ROOT / "docs" / "API.md"


