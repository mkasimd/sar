//! Isolated generator for the WP-6 (M13b) cryptographic conformance vectors.
//!
//! Regenerates only the four fixtures whose bytes encode the superseded KMS
//! payload layout, key hierarchy and AAD:
//!
//! * `valid/crypto/aes256-gcm/aes256_gcm_entry.sar`
//! * `valid/crypto/xchacha20-poly1305/xchacha20_poly1305_entry.sar`
//! * `invalid/crypto/bad-aead-tag/bad_aead_tag.sar`
//! * `invalid/algorithms/unsupported-crypto/unsupported_crypto.sar`
//!
//! Password, salts, KMS parameters and payload are fixed.  Entry nonces are
//! drawn from the OS RNG by the writer, so regenerated bytes are not
//! byte-identical across runs (as before WP-6); they are structurally and
//! cryptographically conformant on every run.
//!
//! Run: `cargo run -p sar-archive --example generate_crypto_vectors`

use std::io::Cursor;
use std::path::{Path, PathBuf};

use sar_archive::{
    ArchiveWriter, ArchiveWriterOptions, CompressionSettings, EncryptionSettings, EntryInput,
};
use sar_core::{
    GlobalFlags, GlobalHeader, KmsData, LocalFileHeader, write_global_header, write_lfh,
};
use sar_crypto::{
    ENCR_AES256_GCM, ENCR_XCHACHA20_POLY, KeyProvider, KmsContext, KmsParams,
    PBKDF2_PRF_HMAC_SHA256, Pbkdf2Params, SarCryptoError, SecretBytes, SecretString,
};

const TEST_PASSWORD_AES: &str = "sar-test-password-aes";
const TEST_PASSWORD_XCHACHA: &str = "sar-test-password-xchacha";

const TEST_SALT_AES: [u8; 32] = [
    0x73, 0x61, 0x72, 0x2d, 0x74, 0x65, 0x73, 0x74, 0x2d, 0x61, 0x65, 0x73, 0x2d, 0x73, 0x61, 0x6c,
    0x74, 0x2d, 0x76, 0x31, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
];

const TEST_SALT_XCHACHA: [u8; 32] = [
    0x73, 0x61, 0x72, 0x2d, 0x74, 0x65, 0x73, 0x74, 0x2d, 0x78, 0x63, 0x68, 0x61, 0x63, 0x68, 0x61,
    0x2d, 0x73, 0x61, 0x6c, 0x74, 0x2d, 0x76, 0x31, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
];

struct StaticPasswordProvider {
    password: SecretString,
}

impl KeyProvider for StaticPasswordProvider {
    fn password_for(&self, _ctx: &KmsContext) -> Result<Option<SecretString>, SarCryptoError> {
        Ok(Some(self.password.clone()))
    }

    fn unwrap_key(
        &self,
        _ctx: &KmsContext,
        _wrapped: &[u8],
    ) -> Result<Option<SecretBytes>, SarCryptoError> {
        Ok(None)
    }

    fn external_key(&self, _ctx: &KmsContext) -> Result<Option<SecretBytes>, SarCryptoError> {
        Ok(None)
    }
}

fn vectors_root() -> PathBuf {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set");
    Path::new(&manifest_dir)
        .parent()
        .and_then(Path::parent)
        .expect("workspace root")
        .join("test-vectors")
}

fn write_fixture(relative_path: &str, bytes: &[u8]) {
    let path = vectors_root().join(relative_path);
    std::fs::write(&path, bytes).expect("write fixture");
    println!("wrote {}", path.display());
}

fn payload() -> Vec<u8> {
    (0..256usize).map(|i| (i & 0xFF) as u8).collect()
}

fn encrypted_archive(
    algo_id: u8,
    salt: &[u8],
    password: &str,
    no_index: bool,
    payload: &[u8],
) -> Vec<u8> {
    let opts = ArchiveWriterOptions {
        no_index,
        encryption: Some(EncryptionSettings {
            algo_id,
            kms_params: KmsParams::Pbkdf2(Pbkdf2Params {
                prf_algo_id: PBKDF2_PRF_HMAC_SHA256,
                salt: salt.to_vec(),
                iterations: 100_000,
                derived_key_length: 32,
            }),
        }),
        ..Default::default()
    };
    let provider: Box<dyn KeyProvider> = Box::new(StaticPasswordProvider {
        password: SecretString::new(password.to_string()),
    });
    let mut buf = Vec::new();
    let mut writer = ArchiveWriter::new_with_compression_and_key_provider(
        Cursor::new(&mut buf),
        opts,
        CompressionSettings::store(),
        Some(provider),
    )
    .expect("writer");
    writer
        .add_entry(EntryInput::file("secret.bin", payload.to_vec()))
        .expect("entry");
    writer.finish().expect("finish");
    buf
}

fn main() {
    let payload = payload();
    write_fixture(
        "valid/crypto/aes256-gcm/aes256_gcm_entry.sar",
        &encrypted_archive(
            ENCR_AES256_GCM,
            &TEST_SALT_AES,
            TEST_PASSWORD_AES,
            false,
            &payload,
        ),
    );
    write_fixture(
        "valid/crypto/xchacha20-poly1305/xchacha20_poly1305_entry.sar",
        &encrypted_archive(
            ENCR_XCHACHA20_POLY,
            &TEST_SALT_XCHACHA,
            TEST_PASSWORD_XCHACHA,
            false,
            &payload,
        ),
    );

    // NO_INDEX so the file ends with the AEAD tag; flip the final 16 bytes.
    let mut bad_tag = encrypted_archive(
        ENCR_AES256_GCM,
        &TEST_SALT_AES,
        TEST_PASSWORD_AES,
        true,
        &payload,
    );
    let len = bad_tag.len();
    for byte in &mut bad_tag[len - 16..] {
        *byte ^= 0xFF;
    }
    write_fixture("invalid/crypto/bad-aead-tag/bad_aead_tag.sar", &bad_tag);

    // IS_ENCRYPTED entry selecting an unsupported CUSTOM Encr Algo ID (0xFE).
    let flags = GlobalFlags::ENCRYPTED | GlobalFlags::NO_INDEX;
    let mut kms_payload = vec![PBKDF2_PRF_HMAC_SHA256];
    kms_payload.extend_from_slice(&100_000u32.to_le_bytes());
    kms_payload.extend_from_slice(&32u16.to_le_bytes());
    kms_payload.push(16);
    kms_payload.extend_from_slice(&[0xAA; 16]);
    let header = GlobalHeader {
        version: 1,
        flags,
        kms: Some(KmsData {
            mode_id: 0x01,
            payload: kms_payload,
        }),
    };
    let mut archive = write_global_header(&header).expect("header");
    let body = b"encrypted payload";
    let mut lfh = LocalFileHeader::minimal_store(b"encrypted.bin".to_vec(), body.len() as u64);
    lfh.entry_mode = sar_core::flags::EntryMode::from_bits(
        lfh.entry_mode.bits() | sar_core::flags::EntryMode::ENCRYPTED,
    );
    lfh.encr_algo_id = Some(0xFE);
    archive.extend_from_slice(&write_lfh(&flags, &lfh).expect("lfh"));
    archive.extend_from_slice(body);
    write_fixture(
        "invalid/algorithms/unsupported-crypto/unsupported_crypto.sar",
        &archive,
    );
}
